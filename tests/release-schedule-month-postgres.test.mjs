import assert from 'node:assert/strict'
import fs from 'node:fs'
import test from 'node:test'
import { PGlite } from '@electric-sql/pglite'

// Disposable embedded PostgreSQL only. Never reads connection settings or opens a remote database.
const migration = fs.readFileSync(new URL(
  '../backend/src/OpmWiki.Infrastructure/Persistence/Migrations/20261002090000_AddReleaseScheduleMonthPrecision.cs',
  import.meta.url), 'utf8')
const sql = name => {
  const match = migration.match(new RegExp(`public const string ${name} = """([\\s\\S]*?)""";`))
  assert.ok(match, `exact ${name} migration SQL is available`)
  return match[1]
}
const up = sql('UpSql')
const down = sql('DownSql')
const fixture = JSON.parse(fs.readFileSync(new URL(
  '../mobile/test/fixtures/api/release_schedule_api_vi.json', import.meta.url), 'utf8'))
const columns = ['Id', 'Server', 'Date', 'CharacterId', 'BannerImage', 'IsReturn', 'OverrideNameVi',
  'OverrideNameEn', 'OverrideTier', 'OverrideFactionVi', 'OverrideFactionEn', 'OverrideTypeVi',
  'OverrideTypeEn', 'OverrideRoleVi', 'OverrideRoleEn', 'SortOrder']
const schema = `
  CREATE TABLE public.release_schedule (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Server" varchar(10) NOT NULL, "Date" date NOT NULL, "CharacterId" varchar(80) NOT NULL,
    "BannerImage" varchar(500) NOT NULL, "IsReturn" boolean NOT NULL,
    "OverrideNameVi" varchar(200) NOT NULL DEFAULT '', "OverrideNameEn" varchar(200) NOT NULL DEFAULT '',
    "OverrideTier" varchar(20) NOT NULL DEFAULT '',
    "OverrideFactionVi" varchar(100) NOT NULL DEFAULT '', "OverrideFactionEn" varchar(100) NOT NULL DEFAULT '',
    "OverrideTypeVi" varchar(100) NOT NULL DEFAULT '', "OverrideTypeEn" varchar(100) NOT NULL DEFAULT '',
    "OverrideRoleVi" varchar(200) NOT NULL DEFAULT '', "OverrideRoleEn" varchar(200) NOT NULL DEFAULT '',
    "SortOrder" integer NOT NULL,
    "CreatedAt" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
  );
  CREATE UNIQUE INDEX "IX_release_schedule_Date_Server_SortOrder"
    ON public.release_schedule ("Date", "Server", "SortOrder");
`

test('exact migration SQL preserves 22 rows, supports month rows and rolls back safely', async t => {
  const db = new PGlite()
  const read = () => db.query('SELECT * FROM public.release_schedule ORDER BY "Id"')
  const count = async () => (await db.query('SELECT count(*)::int AS n FROM public.release_schedule')).rows[0].n
  const childInsert = `INSERT INTO public.release_schedule
    ("Server", "Date", "DatePrecision", "ReleaseMonth", "CharacterId", "BannerImage", "IsReturn", "SortOrder")
    VALUES ($1, $2, $3, $4, '100320-urplus', '/Characters/Child Emperor (UR)/UR.png', false, $5) RETURNING "Id"`
  const expectFailure = async (statement, params, code) => {
    await db.exec('BEGIN')
    try {
      await assert.rejects(db.query(statement, params), error => error.code === code)
    } finally {
      await db.exec('ROLLBACK')
    }
  }
  try {
    await db.exec(schema)
    for (const row of fixture) {
      await db.query(`INSERT INTO public.release_schedule (${columns.map(c => `"${c}"`).join(',')})
        VALUES (${columns.map((_, i) => `$${i + 1}`).join(',')})`,
      columns.map(c => row[c[0].toLowerCase() + c.slice(1)]))
    }
    await db.exec(`SELECT setval(pg_get_serial_sequence('public.release_schedule','Id'),
      (SELECT max("Id") FROM public.release_schedule), true)`)
    const before = (await read()).rows
    assert.equal(before.length, 22)
    await db.exec(`BEGIN; ${up} COMMIT;`)

    await t.test('schema upgrade does not overwrite any original value', async () => {
      const upgraded = (await read()).rows
      assert.deepEqual(upgraded.map(({ DatePrecision, ReleaseMonth, ...row }) => row), before)
      assert.ok(upgraded.every(row => row.DatePrecision === 'day' && row.ReleaseMonth === null))
    })
    let insertedId
    await t.test('month insert is 22 to 23 with NULL exact day and 23 unique keys', async () => {
      insertedId = (await db.query(childInsert, ['CN', null, 'month', '2026-10', 1])).rows[0].Id
      const rows = (await read()).rows
      assert.equal(rows.length, 23)
      const child = rows.find(row => row.Id === insertedId)
      assert.equal(child.Date, null)
      assert.equal(child.ReleaseMonth, '2026-10')
      assert.equal(new Set(rows.map(r => `${r.Server}|${r.Date ?? r.ReleaseMonth}|${r.SortOrder}`)).size, 23)
      const legacy = await db.query(`SELECT count(*)::int AS n FROM public.release_schedule
        WHERE "DatePrecision"='day' AND "Date" IS NOT NULL`)
      assert.equal(legacy.rows[0].n, 22)
    })
    await t.test('duplicate month key fails with 23505 and leaves 23 rows', async () => {
      await expectFailure(childInsert, ['CN', null, 'month', '2026-10', 1], '23505')
      assert.equal(await count(), 23)
    })
    for (const month of ['2026-00', '2026-13', '0000-10', '2026-1']) {
      await t.test(`invalid month ${month} fails with 23514`, async () => {
        await expectFailure(childInsert, ['CN', null, 'month', month, 3], '23514')
      })
    }
    await t.test('month precision plus an exact day fails with 23514', async () => {
      await expectFailure(childInsert, ['CN', '2026-10-01', 'month', '2026-10', 3], '23514')
    })
    await t.test('missing day, missing month and unknown precision fail with 23514', async () => {
      await expectFailure(childInsert, ['CN', null, 'day', null, 3], '23514')
      await expectFailure(childInsert, ['CN', null, 'month', null, 3], '23514')
      await expectFailure(childInsert, ['CN', null, 'other', '2026-10', 3], '23514')
    })
    await t.test('failed post-insert audit rolls back an uncommitted insert', async () => {
      await db.exec('BEGIN')
      await db.query(childInsert, ['CN', null, 'month', '2026-12', 1])
      await assert.rejects(db.exec(`DO $$ BEGIN RAISE EXCEPTION 'synthetic post-audit failure'; END $$;`))
      await db.exec('ROLLBACK')
      assert.equal(await count(), 23)
    })
    await t.test('downgrade aborts before any DDL if a month row remains', async () => {
      await db.exec('BEGIN')
      await assert.rejects(db.exec(down), error => error.code === 'P0001')
      await db.exec('ROLLBACK')
      assert.equal(await count(), 23)
      assert.equal((await db.query(`SELECT "DatePrecision" FROM public.release_schedule WHERE "Id"=$1`, [insertedId])).rows[0].DatePrecision, 'month')
    })
    await t.test('delete only the test-created ID, then downgrade restores all 22 original rows', async () => {
      await db.query('DELETE FROM public.release_schedule WHERE "Id"=$1', [insertedId])
      await db.exec(`BEGIN; ${down} COMMIT;`)
      assert.deepEqual((await read()).rows, before)
      const metadata = await db.query(`SELECT is_nullable FROM information_schema.columns
        WHERE table_schema='public' AND table_name='release_schedule' AND column_name='Date'`)
      assert.equal(metadata.rows[0].is_nullable, 'NO')
    })
  } finally {
    await db.close()
  }
})
